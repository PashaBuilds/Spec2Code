        self.assertIn("#define SHELL_USER_MOD_TEST_TIMEOUT_MS 1000U", user)
        self.assertIn("#define SHELL_USER_MOD_CONNECTOR_COUNT 14U", user)
        self.assertIn('xil_printf("mod: no AXI INTC in this design', user)
