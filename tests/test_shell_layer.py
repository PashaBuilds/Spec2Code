def _zynqmp_spec(name: str) -> dict:
    spec = json.loads((ROOT / "specs/samples/radar_io_board.spec.json").read_text(encoding="utf-8"))
    spec["project"] = {**spec["project"], "name": name}
    return spec


def _generate(spec: dict) -> Path:
    out_dir = Path(tempfile.mkdtemp(prefix="s2c_shell_"))
    codegen.generate(spec, out_dir)
    return out_dir


def _read(out_dir: Path, rel: str) -> str:
    return (out_dir / rel).read_text(encoding="utf-8")


class ShellLayerGenerationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.out_dir = _generate(_axi_spec("unit_shell_gen"))

    @classmethod
    def tearDownClass(cls) -> None:
        shutil.rmtree(cls.out_dir, ignore_errors=True)

    def test_tree_and_no_product_names(self) -> None:
        for rel in ("shell/shell_uart.h", "shell/shell_uart.c", "shell/shell.h", "shell/shell.c", "shell/main.c"):
            self.assertTrue((self.out_dir / rel).is_file(), rel)
            text = _read(self.out_dir, rel).lower().replace("generated by spec2code", "")
            self.assertNotIn("spec2code", text, f"{rel} icinde urun adi")
            self.assertIn(b"\r\n", (self.out_dir / rel).read_bytes())

    def test_api_and_commands(self) -> None:
        header = _read(self.out_dir, "shell/shell.h")
        self.assertIn("void shellInit(SSistemCitBus* spBus, const SSistemCitLimit* spLimit, SSistemCit* spCit);", header)
        self.assertIn("void shellCheck(void);", header)
        self.assertIn("typedef void (*FShellHandler)(unsigned int uiArgc, const char* cpArrArgv[]);", header)
        self.assertIn("unsigned int shellCommandsRegister(const SShellCommand* spTable, unsigned int uiCount);", header)
        source = _read(self.out_dir, "shell/shell.c")
        # Komut tablosu (ad + isleyici + yardim); if-zinciri yok.
        self.assertNotIn("strcmp(cpLine,", source)
        # Cekirdekte komut yok; tum komutlar shell_user_commands.c'deki tek tabloda (kullanici istegi).
        self.assertNotIn("S_sArrBuiltinCommands", source)
        self.assertNotIn("sistemCitRead", source)
