        self.assertIn("while (shellUartByteRead(&ucByte) == TRUE)", source)
        # gecmis: ESC [ A / ESC [ B, halka, ayni komut tek kayit
        self.assertIn("static char S_cArrHistory[SHELL_HISTORY_MAX][SHELL_LINE_MAX];", source)
