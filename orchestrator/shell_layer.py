def write_shell_layer(spec: dict, out_dir: Path, plans: list) -> tuple[list[str], str]:
    """shell/ agacini yazar; (yazilan yollar, README bolumu). CIT plani yoksa bos."""
    if not plans:
        return [], ""
    shell_dir = out_dir / SHELL_DIR
    written = [
        hio.write_output(shell_dir / "shell_uart.h", uart_header()),
        hio.write_output(shell_dir / "shell_uart.c", uart_source(spec)),
        hio.write_output(shell_dir / "shell.h", shell_header()),
        hio.write_output(shell_dir / "shell.c", shell_source(spec, plans)),
        hio.write_output(shell_dir / "main_example.h", main_example_header(spec)),
        hio.write_output(shell_dir / "main_example.c", main_example_source(spec)),
    ]
    return [str(p) for p in written], readme_section(spec, plans)
