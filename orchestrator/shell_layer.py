    e.ln("        }")
    e.ln("        else")
    e.ln("        {")
    e.ln("            /* diger kontrol karakterleri yok sayilir */")
    e.ln("        }")
    e.ln("    }")
    e.ln("}")
    return e.text() + "\n"


