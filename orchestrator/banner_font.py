def render_banner(text: str) -> list[str]:
    """Metni buyuk harfe cevirip Colossal satirlarina doker; bilinmeyen karakter bosluk olur.

    Ust/alt bos satirlar atilir, satir sonlari kirpilir (72+ sutunluk konsollarda
    okunur; uzun adlar terminalde sarabilir - bilincli, font korunur).
    """
    rows = [""] * GLYPH_HEIGHT
    for ch in str(text).upper():
        glyph = _GLYPHS.get(ch) or _GLYPHS[" "]
        for i in range(GLYPH_HEIGHT):
            rows[i] += glyph[i] if i < len(glyph) else " " * len(glyph[0])
    rows = [row.rstrip() for row in rows]
    while rows and not rows[0].strip():
        rows.pop(0)
    while rows and not rows[-1].strip():
        rows.pop()
    return rows
