def _ltc2991_behavior(e: _E, mod: str, pas: str, module: str) -> None:
    """Davranis: donusum tiki (READY kurma + kod uretimi), LSB okununca READY temizleme,
    STATUS_HIGH yaziminda salt okunur bitlerin korunmasi + tek-atis tetik."""
    e.ln(f"void {module}SimKanalAyarla(S{pas}Sim* spSim, unsigned char ucKanal, int iMv)")
    e.ln("{")
    e.ln("    if ((spSim != (S" + pas + "Sim*)0) && (ucKanal < 8U))")
    e.ln("    {")
    e.ln("        spSim->iArrKanalMv[ucKanal] = iMv;")
    e.ln("    }")
    e.ln("}")
    e.blank()
    e.ln(f"void {module}SimSicaklikAyarla(S{pas}Sim* spSim, int iSantiC)")
    e.ln("{")
    e.ln("    if (spSim != (S" + pas + "Sim*)0)")
    e.ln("    {")
    e.ln("        spSim->iSicaklikSantiC = iSantiC;")
    e.ln("    }")
    e.ln("}")
    e.blank()
    e.ln(f"void {module}SimVccAyarla(S{pas}Sim* spSim, int iMv)")
    e.ln("{")
    e.ln("    if (spSim != (S" + pas + "Sim*)0)")
    e.ln("    {")
    e.ln("        spSim->iVccMv = iMv;")
    e.ln("    }")
    e.ln("}")
    e.blank()
    e.ln("/* Tek uclu gerilim kodu: LSB 305.18 uV, 14 bit + isaret, DV biti MSB bit 7. */")
    e.ln(f"static void {module}SimKodYaz(S{pas}Sim* spSim, unsigned char ucMsbReg, int iKod,")
    e.ln("                             unsigned char ucMsbMaske)")
    e.ln("{")
    e.ln("    spSim->ucArrReg[ucMsbReg][0] = (unsigned char)(0x80U | (((unsigned int)iKod >> 8U) & ucMsbMaske));")
    e.ln("    spSim->ucArrReg[ucMsbReg + 1U][0] = (unsigned char)((unsigned int)iKod & 0xFFU);")
    e.ln("}")
    e.blank()
    e.ln("/* Donusum tiki: her okuma islemi oncesi. Repeated Acquisition (0x08 bit 4) ya da")
    e.ln(" * bekleyen tek-atis tetigi varsa etkin kanallarin kodlari uretilir ve READY bitleri")
    e.ln(" * kurulur (2991f: READY, ilgili veri registeri okununca temizlenir). */")
    e.ln(f"static void {module}SimOncesiOku(S{pas}Sim* spSim)")
    e.ln("{")
    e.ln("    unsigned char ucEnable = spSim->ucArrReg[0x01U][0];")
    e.ln("    unsigned int uiTekrar = ((unsigned int)spSim->ucArrReg[0x08U][0] >> 4U) & 0x1U;")
    e.ln("    unsigned char ucCift;")
    e.ln("    int iKod;")
    e.blank()
    e.ln("    if (spSim->uiHataModu == SPEC2CODE_SIM_HATA_HAZIR_YOK)")
    e.ln("    {")
    e.ln("        spSim->ucArrReg[0x00U][0] = 0U;")
    e.ln("        spSim->ucArrReg[0x01U][0] = (unsigned char)(ucEnable & 0xF8U);")
    e.ln("        return;")
    e.ln("    }")
    e.ln("    if ((uiTekrar == 0U) && (spSim->uiTetik == 0U))")
    e.ln("    {")
    e.ln("        return;")
    e.ln("    }")
    e.ln("    spSim->uiTetik = 0U;")
    e.ln("    for (ucCift = 0U; ucCift < 4U; ucCift++)")
    e.ln("    {")
    e.ln("        if (((ucEnable >> (4U + ucCift)) & 0x1U) == 0U)")
    e.ln("        {")
    e.ln("            continue;")
    e.ln("        }")
    e.ln("        iKod = (spSim->iArrKanalMv[2U * ucCift] * 100000) / 30518;")
    e.ln("        if (iKod < 0)")
    e.ln("        {")
    e.ln("            iKod = 0;")
    e.ln("        }")
    e.ln(f"        {module}SimKodYaz(spSim, (unsigned char)(0x0AU + (4U * ucCift)), iKod, 0x3FU);")
    e.ln("        iKod = (spSim->iArrKanalMv[(2U * ucCift) + 1U] * 100000) / 30518;")
    e.ln("        if (iKod < 0)")
    e.ln("        {")
    e.ln("            iKod = 0;")
    e.ln("        }")
    e.ln(f"        {module}SimKodYaz(spSim, (unsigned char)(0x0CU + (4U * ucCift)), iKod, 0x3FU);")
    e.ln("        spSim->ucArrReg[0x00U][0] |= (unsigned char)(0x3U << (2U * ucCift));")
    e.ln("    }")
    e.ln("    if (((ucEnable >> 3U) & 0x1U) != 0U)")
    e.ln("    {")
    e.ln("        /* T_internal: LSB 0.0625 C, 13 bit ikili tumleyen (negatif -> +8192). */")
    e.ln("        iKod = (spSim->iSicaklikSantiC * 4) / 25;")
    e.ln("        if (iKod < 0)")
    e.ln("        {")
    e.ln("            iKod += 8192;")
    e.ln("        }")
    e.ln(f"        {module}SimKodYaz(spSim, 0x1AU, iKod, 0x1FU);")
    e.ln("        iKod = ((spSim->iVccMv - 2500) * 100000) / 30518;")
    e.ln("        if (iKod < 0)")
    e.ln("        {")
    e.ln("            iKod = 0;")
    e.ln("        }")
    e.ln(f"        {module}SimKodYaz(spSim, 0x1CU, iKod, 0x3FU);")
    e.ln("        spSim->ucArrReg[0x01U][0] |= 0x03U; /* VCC_READY + T_INTERNAL_READY */")
    e.ln("    }")
    e.ln("    spSim->ucArrReg[0x01U][0] &= (unsigned char)~0x04U; /* BUSY = 0 */")
    e.ln("}")
    e.blank()
    e.ln("/* Veri registerinin LSB'si okununca o kanalin READY biti temizlenir. */")
    e.ln(f"static void {module}SimSonrasiOku(S{pas}Sim* spSim, unsigned char ucReg)")
    e.ln("{")
    e.ln("    if ((ucReg >= 0x0BU) && (ucReg <= 0x19U) && ((ucReg & 0x1U) != 0U))")
    e.ln("    {")
    e.ln("        spSim->ucArrReg[0x00U][0] &= (unsigned char)~(1U << ((ucReg - 0x0BU) / 2U));")
    e.ln("    }")
    e.ln("    else if (ucReg == 0x1BU)")
    e.ln("    {")
    e.ln("        spSim->ucArrReg[0x01U][0] &= (unsigned char)~0x02U;")
    e.ln("    }")
    e.ln("    else if (ucReg == 0x1DU)")
    e.ln("    {")
    e.ln("        spSim->ucArrReg[0x01U][0] &= (unsigned char)~0x01U;")
    e.ln("    }")
    e.ln("}")
    e.blank()
    e.ln("/* STATUS_HIGH'in READY/BUSY bitleri salt okunur; yazim tek-atis tetigi sayilir. */")
    e.ln(f"static void {module}SimSonrasiYaz(S{pas}Sim* spSim, unsigned char ucReg, unsigned char ucEski)")
    e.ln("{")
    e.ln("    if (ucReg == 0x01U)")
    e.ln("    {")
    e.ln("        spSim->ucArrReg[0x01U][0] = (unsigned char)((spSim->ucArrReg[0x01U][0] & 0xF8U) | (ucEski & 0x07U));")
    e.ln("        spSim->uiTetik = 1U;")
    e.ln("    }")
    e.ln("}")
    e.blank()
    _ = mod


