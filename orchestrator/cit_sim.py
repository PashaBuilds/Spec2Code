"""CIT simulasyon katmani: descriptor'dan uretilen sanal I2C cihazlari (cit/sim/).

Her I2C register cihazi icin ``<mod>_sim.h/.c`` uretilir: register dosyasi
(reset degerleri, genislik ve yazilabilirlik tablolari descriptor'dan), pointer +
otomatik artis ile bayt bayt okuma/yazma, hata enjeksiyonu (NACK, hazir biti hic
gelmez) ve entegreye ozel DAVRANIS bloklari (``_BEHAVIOR`` tablosu: LTC2991 icin
READY bit dinamigi + hedef mV/santi-C'den dönüşüm kodlari).

Sanal cihaz HAL'e ``spec2codeI2cSimEkle`` ile takilir; adres eslesirse cevabi
simulator verir, eslesmezse transfer gercek donanima gider (karisik mod).
"""

from __future__ import annotations

from typing import Callable

from orchestrator.cit_layer import _E, _ChipPlan, _hex, _pascal

SIM_HATA_YOK = "SPEC2CODE_SIM_HATA_YOK"
SIM_HATA_NACK = "SPEC2CODE_SIM_HATA_NACK"
SIM_HATA_HAZIR_YOK = "SPEC2CODE_SIM_HATA_HAZIR_YOK"


def sim_plans(plans: list[_ChipPlan]) -> list[_ChipPlan]:
    """Simulatoru uretilen cihazlar: I2C register cihazlari + SPI TICS-register cihazlari."""
    return [p for p in plans if p.transport in {"i2c", "spi"}]


def _reg_table(plan: _ChipPlan) -> tuple[int, int, list[tuple[int, int, int, int, str]]]:
    """(register sayisi, en genis bayt, [(offset, bayt, yazilabilir, reset, ad)])."""
    rows: list[tuple[int, int, int, int, str]] = []
    max_off = 0
    max_bytes = 1
    for rg in plan.descriptor.get("registers", []):
        off = int(rg.get("offset", 0))
        width = int(rg.get("width", 8) or 8)
        if width > 32 or off > 255:
            continue
        nbytes = max(1, (width + 7) // 8)
        access = str(rg.get("access", "rw")).lower()
        writable = 1 if "w" in access else 0
        reset = int(rg.get("reset", 0) or 0)
        rows.append((off, nbytes, writable, reset, str(rg.get("name", ""))))
        max_off = max(max_off, off)
        max_bytes = max(max_bytes, nbytes)
    return max_off + 1, max_bytes, rows


