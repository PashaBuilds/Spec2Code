    e.ln(" * RESET_ENABLE (CONFIGURATION bit 2) ile sayaclar sifirlanir; ALARM_FLAG/EVENT MSB salt okunur. */")
    e.ln(f"static void {module}SimSonrasiYaz(S{pas}Sim* spSim, unsigned char ucReg, unsigned char ucEski)")
    e.ln("{")
    e.ln("    if (ucReg == 0x00U)")
    e.ln("    {")
