"""CIT simulasyon katmani: descriptor'dan uretilen sanal I2C cihazlari (cit/sim/).

Her I2C register cihazi icin ``<mod>_sim.h/.c`` uretilir: register dosyasi
(reset degerleri, genislik ve yazilabilirlik tablolari descriptor'dan), pointer +
otomatik artis ile bayt bayt okuma/yazma, hata enjeksiyonu (NACK, hazir biti hic
gelmez) ve entegreye ozel DAVRANIS bloklari (``_BEHAVIOR`` tablosu: LTC2991 icin
READY bit dinamigi + hedef mV/santi-C'den dönüşüm kodlari).

Sanal cihaz HAL'e ``spec2codeI2cSimEkle`` ile takilir; adres eslesirse cevabi
simulator verir, eslesmezse transfer gercek donanima gider (karisik mod).
"""

from __future__ import annotations

from typing import Callable

from orchestrator.cit_layer import _E, _ChipPlan, _hex, _pascal

