def sim_source(plan: _ChipPlan) -> str:
    mod, pas, module = plan.mod, plan.pascal, plan.module
    reg_count, max_bytes, rows = _reg_table(plan)
    beh = _BEHAVIOR.get(plan.part.upper())
    by_off = {r[0]: r for r in rows}
    e = _E(0)
    e.ln("/**")
    e.ln(f" * @file {module}_sim.c")
    e.ln(f" * @brief {plan.part} sanal cihazi gerceklemesi. Generated by Spec2Code.")
    e.ln(" *")
    e.ln(" * Register modeli: yazma transferinin ilk bayti pointer'dir, kalan baytlar")
    e.ln(" * pointer'dan itibaren yazilir (salt okunur register ACK alir ama degismez);")
    e.ln(" * okuma pointer'dan baslar, genis registerin baytlari bittikce sonraki")
    e.ln(" * register'a gecer (I2C otomatik artis).")
    e.ln(" */")
    e.ln(f'#include "{module}_sim.h"')
    e.blank()
    e.ln("#if SPEC2CODE_CIT_SIM")
    e.blank()
    e.ln("/* Register basina bayt genisligi (0 = descriptor'da tanimsiz: 1 bayt, sifir okunur). */")
    e.ln(f"static const unsigned char S_ucArr{pas}SimGenislik[{mod}_SIM_REG_SAYISI] = " + "{")
    e.ln("    " + ", ".join(f"{by_off[i][1] if i in by_off else 0}U" for i in range(reg_count)))
    e.ln("};")
    e.blank()
    e.ln("/* Register basina yazilabilirlik (rw/wo = 1). */")
    e.ln(f"static const unsigned char S_ucArr{pas}SimYazilabilir[{mod}_SIM_REG_SAYISI] = " + "{")
    e.ln("    " + ", ".join(f"{by_off[i][2] if i in by_off else 0}U" for i in range(reg_count)))
    e.ln("};")
    e.blank()
    e.ln("/* Reset degerleri (descriptor `reset`, MSB once). */")
    e.ln(f"static const unsigned char S_ucArr{pas}SimReset[{mod}_SIM_REG_SAYISI][{mod}_SIM_BAYT_MAX] = " + "{")
    for i in range(reg_count):
        if i in by_off:
            off, nbytes, _w, reset, name = by_off[i]
            vals = [(reset >> (8 * (nbytes - 1 - k))) & 0xFF for k in range(nbytes)]
            vals += [0] * (max_bytes - nbytes)
            e.ln("    {" + ", ".join(_hex(v) for v in vals) + "}," + f" /* {name} */")
        else:
            e.ln("    {" + ", ".join("0x00U" for _ in range(max_bytes)) + "},")
    e.ln("};")
    e.blank()
    e.ln(f"static unsigned char {module}SimGenislik(unsigned char ucReg)")
    e.ln("{")
    e.ln(f"    if (ucReg >= {mod}_SIM_REG_SAYISI)")
    e.ln("    {")
    e.ln("        return 1U;")
    e.ln("    }")
    e.ln(f"    return (S_ucArr{pas}SimGenislik[ucReg] == 0U) ? 1U : S_ucArr{pas}SimGenislik[ucReg];")
    e.ln("}")
    e.blank()
    if beh:
        beh["behavior"](e, mod, pas, module)
    # --- HAL geri cagrilari ---
    e.ln(f"static int {module}SimYaz(void* vpDurum, const unsigned char* ucpVeri, unsigned int uiBoy)")
    e.ln("{")
    e.ln(f"    S{pas}Sim* spSim = (S{pas}Sim*)vpDurum;")
    e.ln("    unsigned int uiIndex;")
    e.ln("    unsigned char ucReg;")
    e.ln("    unsigned char ucBayt;")
    e.ln("    unsigned char ucEski;")
    e.blank()
    e.ln("    if (spSim->uiHataModu == SPEC2CODE_SIM_HATA_NACK)")
    e.ln("    {")
    e.ln("        return 1;")
    e.ln("    }")
    e.ln("    if (uiBoy == 0U)")
    e.ln("    {")
    e.ln("        return 0; /* yalniz adres probe'u: ACK */")
    e.ln("    }")
    e.ln("    spSim->uiYazmaSayac++;")
    e.ln("    spSim->ucPointer = ucpVeri[0];")
    e.ln("    spSim->ucBaytIndeks = 0U;")
    e.ln("    ucReg = spSim->ucPointer;")
    e.ln("    ucBayt = 0U;")
    e.ln("    for (uiIndex = 1U; uiIndex < uiBoy; uiIndex++)")
    e.ln("    {")
    e.ln(f"        if (ucReg < {mod}_SIM_REG_SAYISI)")
    e.ln("        {")
    e.ln("            ucEski = spSim->ucArrReg[ucReg][ucBayt];")
    e.ln(f"            if (S_ucArr{pas}SimYazilabilir[ucReg] != 0U)")
    e.ln("            {")
    e.ln("                spSim->ucArrReg[ucReg][ucBayt] = ucpVeri[uiIndex];")
    if beh:
        e.ln(f"                {module}SimSonrasiYaz(spSim, ucReg, ucEski);")
    e.ln("            }")
    if not beh:
        e.ln("            (void)ucEski;")
    e.ln("        }")
    e.ln("        ucBayt++;")
    e.ln(f"        if (ucBayt >= {module}SimGenislik(ucReg))")
    e.ln("        {")
    e.ln("            ucBayt = 0U;")
    e.ln("            ucReg++;")
    e.ln("        }")
    e.ln("    }")
    e.ln("    return 0;")
    e.ln("}")
    e.blank()
    e.ln(f"static int {module}SimOku(void* vpDurum, unsigned char* ucpVeri, unsigned int uiBoy)")
    e.ln("{")
    e.ln(f"    S{pas}Sim* spSim = (S{pas}Sim*)vpDurum;")
    e.ln("    unsigned int uiIndex;")
    e.blank()
    e.ln("    if (spSim->uiHataModu == SPEC2CODE_SIM_HATA_NACK)")
    e.ln("    {")
    e.ln("        return 1;")
    e.ln("    }")
    e.ln("    spSim->uiOkumaSayac++;")
    if beh:
        e.ln(f"    {module}SimOncesiOku(spSim);")
    e.ln("    for (uiIndex = 0U; uiIndex < uiBoy; uiIndex++)")
    e.ln("    {")
    e.ln(f"        if (spSim->ucPointer < {mod}_SIM_REG_SAYISI)")
    e.ln("        {")
    e.ln("            ucpVeri[uiIndex] = spSim->ucArrReg[spSim->ucPointer][spSim->ucBaytIndeks];")
    e.ln("        }")
    e.ln("        else")
    e.ln("        {")
    e.ln("            ucpVeri[uiIndex] = 0xFFU;")
    e.ln("        }")
    e.ln("        spSim->ucBaytIndeks++;")
    e.ln(f"        if (spSim->ucBaytIndeks >= {module}SimGenislik(spSim->ucPointer))")
    e.ln("        {")
    if beh:
        e.ln(f"            {module}SimSonrasiOku(spSim, spSim->ucPointer);")
    e.ln("            spSim->ucBaytIndeks = 0U;")
    e.ln("            spSim->ucPointer++;")
    e.ln("        }")
    e.ln("    }")
    e.ln("    return 0;")
    e.ln("}")
    e.blank()
    e.ln(f"void {module}SimKur(S{pas}Sim* spSim, unsigned char ucAdres)")
    e.ln("{")
    e.ln("    unsigned int uiIndex;")
    e.ln("    unsigned int uiBayt;")
    e.blank()
    e.ln(f"    if (spSim == (S{pas}Sim*)0)")
    e.ln("    {")
    e.ln("        return;")
    e.ln("    }")
    e.ln(f"    for (uiIndex = 0U; uiIndex < {mod}_SIM_REG_SAYISI; uiIndex++)")
    e.ln("    {")
    e.ln(f"        for (uiBayt = 0U; uiBayt < {mod}_SIM_BAYT_MAX; uiBayt++)")
    e.ln("        {")
    e.ln(f"            spSim->ucArrReg[uiIndex][uiBayt] = S_ucArr{pas}SimReset[uiIndex][uiBayt];")
    e.ln("        }")
    e.ln("    }")
    e.ln("    spSim->ucPointer = 0U;")
    e.ln("    spSim->ucBaytIndeks = 0U;")
    e.ln("    spSim->uiHataModu = SPEC2CODE_SIM_HATA_YOK;")
    e.ln("    spSim->uiYazmaSayac = 0U;")
    e.ln("    spSim->uiOkumaSayac = 0U;")
    if beh:
        beh["kur"](e)
    e.ln("    spSim->sCihaz.ucAdres = ucAdres;")
    e.ln("    spSim->sCihaz.vpDurum = spSim;")
    e.ln(f"    spSim->sCihaz.pfYaz = {module}SimYaz;")
    e.ln(f"    spSim->sCihaz.pfOku = {module}SimOku;")
    e.ln("    spSim->sCihaz.spSonraki = (SSpec2codeI2cSimCihaz*)0;")
    e.ln("}")
    e.blank()
    e.ln(f"void {module}SimHataAyarla(S{pas}Sim* spSim, unsigned int uiHataModu)")
    e.ln("{")
    e.ln(f"    if (spSim != (S{pas}Sim*)0)")
    e.ln("    {")
    e.ln("        spSim->uiHataModu = uiHataModu;")
    e.ln("    }")
    e.ln("}")
    e.blank()
    e.ln(f"void {module}SimRegisterYaz(S{pas}Sim* spSim, unsigned char ucReg, unsigned char ucBayt,")
