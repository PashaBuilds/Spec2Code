def sistem_sim_source_section(spec: dict, plans: list[_ChipPlan], controller_field: Callable[[dict], str],
                              device_field: Callable[[dict], str]) -> list[str]:
    sims = sim_plans(plans)
    if not sims:
        return []
    used_i2c = {p.controller["id"] for p in sims}
    muxes = [m for m in spec.get("muxes", []) if m.get("controller_id") in used_i2c]
    controllers = {c["id"]: c for c in spec.get("controllers", [])}
    e = _E(0)
    e.ln("#if SPEC2CODE_CIT_SIM")
    e.ln("void sistemCitSimKur(SSistemCitSim* spSim)")
    e.ln("{")
    e.ln("    if (spSim == (SSistemCitSim*)0)")
    e.ln("    {")
    e.ln("        return;")
    e.ln("    }")
    for m in muxes:
        e.ln(f"    spec2codeI2cSimSwitchKur(&spSim->{device_field(m)}, {_hex(int(str(m['i2c_address']), 0))});")
    for p in sims:
        e.ln(f"    {p.module}SimKur(&spSim->{device_field(p.device)}, {p.mod}_CIT_I2C_ADDR);")
    e.ln("}")
    e.blank()
    e.ln("int sistemCitSimEkle(SSistemCitBus* spBus, SSistemCitSim* spSim)")
    e.ln("{")
    e.ln("    int iIlkHata = SPEC2CODE_CIT_OK;")
    e.ln("    int iStatus;")
    e.blank()
    e.ln("    if ((spBus == (SSistemCitBus*)0) || (spSim == (SSistemCitSim*)0))")
    e.ln("    {")
    e.ln("        return SPEC2CODE_CIT_PARAMETRE;")
    e.ln("    }")
    for p in sims:
        e.ln(f"    iStatus = spec2codeI2cSimEkle(&spBus->{controller_field(p.controller)}, "
             f"&spSim->{device_field(p.device)}.sCihaz);")
        e.ln("    if ((iStatus != SPEC2CODE_CIT_OK) && (iIlkHata == SPEC2CODE_CIT_OK))")
        e.ln("    {")
        e.ln("        iIlkHata = iStatus;")
        e.ln("    }")
    e.ln("    return iIlkHata;")
    e.ln("}")
    if muxes:
        e.blank()
        e.ln("int sistemCitSimSwitchEkle(SSistemCitBus* spBus, SSistemCitSim* spSim)")
        e.ln("{")
        e.ln("    int iIlkHata = SPEC2CODE_CIT_OK;")
        e.ln("    int iStatus;")
        e.blank()
        e.ln("    if ((spBus == (SSistemCitBus*)0) || (spSim == (SSistemCitSim*)0))")
        e.ln("    {")
        e.ln("        return SPEC2CODE_CIT_PARAMETRE;")
        e.ln("    }")
        for m in muxes:
            c = controllers[m["controller_id"]]
            e.ln(f"    iStatus = spec2codeI2cSimEkle(&spBus->{controller_field(c)}, &spSim->{device_field(m)}.sCihaz);")
            e.ln("    if ((iStatus != SPEC2CODE_CIT_OK) && (iIlkHata == SPEC2CODE_CIT_OK))")
            e.ln("    {")
            e.ln("        iIlkHata = iStatus;")
            e.ln("    }")
        e.ln("    return iIlkHata;")
        e.ln("}")
    e.ln("#endif /* SPEC2CODE_CIT_SIM */")
    return e.lines
